export function tripCopy(language, key, ...args) {
  const locale = String(language || "en").split("-")[0];
  const value = COPY[locale]?.[key] ?? COPY.en[key];
  return typeof value === "function" ? value(...args) : value;
}

export function tripPriceRange(language, min, max, currency) {
  const locale = String(language || "en").split("-")[0];
  if (locale === "fr") return `${min} – ${max} ${currency}`;
  return `${min} – ${max} ${currency}`;
}
